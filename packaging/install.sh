# Install, upgrade or remove os-mdns-bridge on OPNsense.
#
#   sh install.sh             install, or upgrade an existing installation
#   sh install.sh uninstall   remove the plugin, the daemon and the repository
#
# What it does:
#   1. adds the os-mdns-bridge pkg repository and its signing key
#   2. backs up /conf/config.xml to /root before changing anything
#   3. removes files left by 0.1 development installs that no package owns
#   4. installs or upgrades os-mdns-bridge and mdns-bridge from that repository
#
# Your settings live in /conf/config.xml and are never removed by this
# script or by pkg. Settings from plugin 0.1 are migrated automatically.
# After installation, future updates arrive through System > Firmware
# like any other package.

set -eu

SITE=${MDNSBRIDGE_SITE:-https://patricktryan.github.io/os-mdns-bridge}
REPO_NAME=mdnsbridge
REPO_CONF=/usr/local/etc/pkg/repos/${REPO_NAME}.conf
KEY_DIR=/usr/local/etc/pkg/keys
KEY_FILE=${KEY_DIR}/${REPO_NAME}.pub

die() { echo "ERROR: $*" >&2; exit 1; }
say() { echo ">>> $*"; }

[ "$(id -u)" = 0 ] || die "run as root"
command -v opnsense-version > /dev/null || die "this does not look like OPNsense"

uninstall()
{
	say "Stopping and removing os-mdns-bridge and mdns-bridge"
	/usr/local/etc/rc.d/mdns_bridge onestop > /dev/null 2>&1 || true
	pkg delete -y os-mdns-bridge mdns-bridge 2> /dev/null || true
	rm -f /etc/rc.conf.d/mdns_bridge /var/run/mdns_bridge.carp_master \
	    /usr/local/etc/mdns-bridge.conf "${REPO_CONF}" "${KEY_FILE}"
	say "Removed. Your mDNS Bridge settings remain in /conf/config.xml and"
	say "will be used again if you reinstall."
	exit 0
}

[ "${1:-}" = uninstall ] && uninstall
[ -z "${1:-}" ] || die "usage: sh install.sh [uninstall]"

say "OPNsense $(opnsense-version -v), ABI $(pkg config ABI)"
ABI_DIR=$(pkg config ABI | tr 'A-Z:' 'a-z-')
URL=${SITE}/repo/${ABI_DIR}

# --- 1. repository ----------------------------------------------------------
TMP=$(mktemp -d)
trap 'rm -rf "${TMP}"' EXIT

fetch -q -o "${TMP}/meta.conf" "${URL}/meta.conf" 2> /dev/null || \
    die "no packages published for $(pkg config ABI) at ${URL}"
fetch -q -o "${TMP}/key.pub" "${SITE}/mdnsbridge.pub" || die "cannot fetch the signing key"
grep -q "BEGIN PUBLIC KEY" "${TMP}/key.pub" || die "the downloaded signing key is not a public key"

mkdir -p "${KEY_DIR}" "$(dirname "${REPO_CONF}")"
if [ -f "${KEY_FILE}" ] && ! cmp -s "${KEY_FILE}" "${TMP}/key.pub"; then
	die "the published signing key differs from ${KEY_FILE}. If the key was rotated on purpose (see the project README), delete ${KEY_FILE} and run this script again."
fi
install -m 0644 "${TMP}/key.pub" "${KEY_FILE}"

cat > "${REPO_CONF}" <<CONF
# os-mdns-bridge package repository, added by install.sh.
# Remove this file and ${KEY_FILE} to stop receiving updates.
${REPO_NAME}: {
  url: "${URL}",
  signature_type: "pubkey",
  pubkey: "${KEY_FILE}",
  enabled: yes
}
CONF
say "Repository configured: ${REPO_CONF}"

# --- 2. backups ---------------------------------------------------------------
STAMP=$(date +%Y%m%d-%H%M%S)
cp -p /conf/config.xml "/root/config.xml.before-mdns-bridge-${STAMP}"
say "Configuration backed up to /root/config.xml.before-mdns-bridge-${STAMP}"

# A hand-written daemon config (not generated by the plugin) is kept aside;
# from now on the plugin generates this file from the GUI settings.
if [ -f /usr/local/etc/mdns-bridge.conf ] && \
    ! grep -q "Generated by" /usr/local/etc/mdns-bridge.conf; then
	cp -p /usr/local/etc/mdns-bridge.conf "/root/mdns-bridge.conf.before-plugin-${STAMP}"
	say "Hand-written mdns-bridge.conf saved to /root/mdns-bridge.conf.before-plugin-${STAMP}"
fi

# --- 3. leftovers from 0.1 development installs ------------------------------
# Only files that no package owns are removed.
for f in \
    /usr/local/opnsense/scripts/OPNsense/MDNSBridge/carp_reconcile.php \
    /usr/local/opnsense/service/templates/OPNsense/MDNSBridge/mdnsbridge \
    /usr/local/opnsense/service/templates/OPNsense/MDNSBridge/mdnsbridge_rc \
    /var/run/mdns_bridge.CARP_MASTER \
    /var/run/mdns_bridge.carp.lock; do
	if [ -e "${f}" ] && ! pkg which -q "${f}" > /dev/null 2>&1; then
		rm -f "${f}"
		say "Removed obsolete ${f}"
	fi
done

# --- 4. packages ----------------------------------------------------------------
pkg update -f -r "${REPO_NAME}"

if pkg info -e os-mdns-bridge; then
	say "Upgrading os-mdns-bridge $(pkg query %v os-mdns-bridge)"
	pkg upgrade -y -r "${REPO_NAME}" os-mdns-bridge mdns-bridge
else
	say "Installing os-mdns-bridge"
	pkg install -y -r "${REPO_NAME}" os-mdns-bridge
fi

say "Installed: os-mdns-bridge $(pkg query %v os-mdns-bridge), mdns-bridge $(pkg query %v mdns-bridge)"
say "Configure it under Services > mDNS Bridge. Future updates arrive via System > Firmware."
